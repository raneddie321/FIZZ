// Writes static-site/assets/agent-core.js: the browser copy of netlify/lib/agent-core.mjs (as window.FIZZ.agentCore).
// Run after editing the .mjs:  node scripts/build-agent-core.mjs
import { readFileSync, writeFileSync } from "node:fs";
const src = readFileSync(new URL("../netlify/lib/agent-core.mjs", import.meta.url), "utf8");
if (/^\s*import\s/m.test(src)) throw new Error("agent-core.mjs must not import anything: it also runs in the browser.");
const names = [...src.matchAll(/^export (?:async )?(?:function\*?|const|let|class) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]);
const body = src.replace(/^export /gm, "").split("\n").map((l) => (l ? `  ${l}` : l)).join("\n");
const out = `/* Generated by scripts/build-agent-core.mjs from netlify/lib/agent-core.mjs — don't edit by hand. */
(function () {
  "use strict";
${body}
  window.FIZZ.agentCore = { ${names.join(", ")} };
})();
`;
writeFileSync(new URL("../static-site/assets/agent-core.js", import.meta.url), out);
console.log(`wrote static-site/assets/agent-core.js (${names.length} exports)`);
